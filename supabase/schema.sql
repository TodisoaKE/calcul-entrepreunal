create table if not exists public.simulations (
  id bigint generated by default as identity primary key,
  name text not null,
  mode text not null check (mode in ('target', 'forecast')),
  target_net numeric(16, 0) not null default 0 check (target_net >= 0),
  monthly_turnover numeric(16, 0) not null default 0 check (monthly_turnover >= 0),
  fixed_costs numeric(16, 0) not null default 0 check (fixed_costs >= 0),
  variable_rate numeric(5, 2) not null default 0 check (variable_rate between 0 and 80),
  social_rate numeric(5, 2) not null default 0 check (social_rate between 0 and 80),
  reserve_months integer not null default 3 check (reserve_months between 1 and 12),
  saved_at timestamptz not null default now(),
  created_by uuid not null default auth.uid()
);

create table if not exists public.family_members (
  user_id uuid primary key references auth.users (id) on delete cascade,
  added_at timestamptz not null default now()
);

alter table public.family_members enable row level security;
alter table public.simulations enable row level security;

revoke all on table public.family_members from anon, authenticated, public;
revoke all on table public.simulations from anon, public;
grant select, insert, delete on table public.simulations to authenticated;
grant usage, select on sequence public.simulations_id_seq to authenticated;

create or replace function public.is_family_member()
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select exists (
    select 1 from public.family_members
    where user_id = (select auth.uid())
  );
$$;

revoke all on function public.is_family_member() from public, anon;
grant execute on function public.is_family_member() to authenticated;

drop policy if exists "Signed-in family can read simulations" on public.simulations;
create policy "Signed-in family can read simulations"
  on public.simulations for select to authenticated
  using ((select public.is_family_member()));

drop policy if exists "Signed-in family can add simulations" on public.simulations;
create policy "Signed-in family can add simulations"
  on public.simulations for insert to authenticated
  with check ((select public.is_family_member()) and created_by = (select auth.uid()));

drop policy if exists "Signed-in family can delete simulations" on public.simulations;
create policy "Signed-in family can delete simulations"
  on public.simulations for delete to authenticated
  using ((select public.is_family_member()));
